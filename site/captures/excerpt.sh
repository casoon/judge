#!/usr/bin/env bash
# Writes the start-page scene judge.terminal.yaml from the captured judge output in
# examples/ (written by examples/capture.sh). Nothing is run, nothing is reworded:
# - `cargo judge`: the first 12 lines of examples/summary.ansi (the last one empty), with their real colours;
# - `cargo judge compare`: the count lines of examples/compare.txt (verdict, unchanged,
#   resolved, introduced, introduced advisory, severity changed), without the finding lists.
# The full output of both runs is in the showcase. Rebuild the scenes afterwards:
#   cd site/captures && for f in judge.terminal.yaml judge-narrow.terminal.yaml; do
#     npx -y -p @casoon/castwright@0.5.0 -p shiki castwright build "$f" --format svg -o .; done
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
examples="$here/../../examples"

# One YAML double-quoted string: ESC as \e, line ends as \r\n, quotes and backslashes escaped.
yaml_raw() {
  perl -0pe 's/\\/\\\\/g; s/"/\\"/g; s/\e/\\e/g; s/\n/\\r\\n/g; $_ = "\"$_\""'
}

summary="$(head -n 12 "$examples/summary.ansi" | yaml_raw)"
compare="$(grep -E '^(verdict|unchanged|resolved|introduced|introduced advisory .*|severity changed):' \
  "$examples/compare.txt" | yaml_raw)"

# scene <file> <cols> <rows>: the same steps; the narrow one is for phones, where the
# two long lines wrap at a word boundary, like in a real terminal, instead of
# shrinking the text.
scene() {
  cat > "$here/$1" <<YAML
# Generated by excerpt.sh from examples/summary.ansi and examples/compare.txt: excerpts of
# real judge 0.7.0 runs on its own source tree. Edit excerpt.sh, not this file.
version: 1
terminal:
  title: cargo judge
  cols: $2
  rows: $3
  theme: catppuccin-mocha
steps:
  - run: cargo judge
  - wait: 600
  - output:
      raw: $summary
  - wait: 1800
  - run: cargo judge compare .judge/baseline.json
  - wait: 600
  - output:
      raw: $compare
  - wait: 5000
YAML
}

scene judge.terminal.yaml 66 22
scene judge-narrow.terminal.yaml 53 24
